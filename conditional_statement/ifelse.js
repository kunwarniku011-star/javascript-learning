//conditional statement are used to execute different blocks of code based on specific condition
//synatx if(condition){//statement}
//if else
let marks=25;
if(marks>=33){
    console.log("pass");
}
else{
    console.log("fail")
}
//switch statement executes a matching case based on the value of an expression
let day=2;
switch(day){
    case 1:
        console.log("monday");
        break;
    case 2:
        console.log("tuesday");
        break;
    default:
        console.log("invalid day");
}


